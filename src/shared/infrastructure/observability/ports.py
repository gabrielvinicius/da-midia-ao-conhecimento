from __future__ import annotations

from typing import Any, Protocol


class MetricsPort(Protocol):
    async def record_operation(self, **kwargs) -> Any: ...
    def set_context(self, *args, **kwargs) -> Any: ...
    # Optional sync variant for Celery sync paths
    def record_operation_sync(self, **kwargs) -> Any: ...


class LoggerPort(Protocol):
    async def log_operation(self, **kwargs) -> Any: ...
    def info(self, message: str, **kwargs) -> Any: ...
    def warning(self, message: str, **kwargs) -> Any: ...
    def error(self, message: str, **kwargs) -> Any: ...


__all__ = ["MetricsPort", "LoggerPort"]

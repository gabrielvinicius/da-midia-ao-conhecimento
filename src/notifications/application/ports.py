from __future__ import annotations

from typing import Any, Optional, Protocol
from uuid import UUID

from src.notifications.domain import Notification
from src.shared.infrastructure.observability.ports import (
    MetricsPort as SharedMetricsPort,
)


class AuthQueriesPort(Protocol):
    async def get_user_by_id(self, user_id): ...
    async def get_user_by_email(self, email: str): ...
    async def list_all(self, page: int, limit: int, search: Optional[str] = None): ...
    async def count_filtered(self, search: Optional[str] = None) -> int: ...


class NotificationRepositoryPort(Protocol):
    async def find_by_id(self, notification_id: UUID) -> Optional[Notification]: ...
    async def save(self, notification: Notification) -> Notification: ...
    async def list_by_user(self, user_id: str): ...
    async def delete(self, notification_id: str) -> bool: ...
    async def mark_as_read(self, notification_id: str) -> bool: ...
    async def mark_as_delivered(self, notification_id: str) -> bool: ...
    async def list_undelivered_by_user(self, user_id: str, limit: int = 50): ...
    async def count_all(self) -> int: ...
    async def count_unread_all(self) -> int: ...
    async def count_by_user_id(self, user_id: UUID) -> int: ...
    async def count_unread_by_user_id(self, user_id: UUID) -> int: ...
    async def delete_older_than(self, days_to_keep: int) -> int: ...


class NotificationDeliveryPort(Protocol):
    async def send_to_user(self, user_id: UUID, payload: Any) -> bool: ...


class NotificationLoggerPort(Protocol):
    async def log_operation(
        self,
        *,
        operation: str,
        success: bool,
        duration: float,
        **extra: Any,
    ) -> None: ...
    def info(self, message: str, **extra: Any) -> None: ...
    def warning(self, message: str, **extra: Any) -> None: ...
    def error(self, message: str, **extra: Any) -> None: ...


class NotificationMetricsPort(SharedMetricsPort, Protocol):
    async def record_notification_sent(self, channel: str) -> None: ...


__all__ = [
    "AuthQueriesPort",
    "NotificationRepositoryPort",
    "NotificationDeliveryPort",
    "NotificationLoggerPort",
    "NotificationMetricsPort",
]
